-- ============================================================================
-- Row Level Security
--
-- The operator has chosen to run the agent with only the Supabase publishable
-- key (no service role key configured yet). PostgREST enforces RLS, so with
-- RLS enabled and no policies, every request from the agent would be
-- rejected. The policies below are the permissive set required to make the
-- agent work TODAY under that constraint — each is commented with exactly
-- what it exposes. A hardened, commented-out alternative follows for when a
-- service role key becomes available: the service role bypasses RLS
-- entirely, so those policies simply lock the publishable key back down to
-- read-only (or nothing).
-- ============================================================================

alter table markets           enable row level security;
alter table decisions         enable row level security;
alter table positions         enable row level security;
alter table orders            enable row level security;
alter table market_snapshots  enable row level security;
alter table metrics           enable row level security;
alter table graph_runs        enable row level security;
alter table graph_nodes       enable row level security;
alter table graph_edges       enable row level security;
alter table onchain_anchors   enable row level security;
alter table trace_blobs       enable row level security;
alter table breaker_state     enable row level security;
alter table blocklist         enable row level security;
alter table llm_usage         enable row level security;
alter table treasury          enable row level security;
alter table treasury_events   enable row level security;
alter table flywheel_events   enable row level security;

-- Anyone holding the publishable key, which ships in the browser bundle, can
-- read every table below (market data, the agent's trading ledger, its
-- reasoning traces, and on-chain anchor records). This matches what the
-- existing web app already surfaces through the API, so it is not a new
-- exposure, but it is broader than "read your own rows" — there is no
-- per-viewer scoping.
create policy "public read markets"          on markets           for select using (true);
create policy "public read decisions"        on decisions         for select using (true);
create policy "public read positions"        on positions         for select using (true);
create policy "public read orders"           on orders            for select using (true);
create policy "public read market_snapshots" on market_snapshots  for select using (true);
create policy "public read metrics"          on metrics           for select using (true);
create policy "public read graph_runs"       on graph_runs        for select using (true);
create policy "public read graph_nodes"      on graph_nodes       for select using (true);
create policy "public read graph_edges"      on graph_edges       for select using (true);
create policy "public read onchain_anchors"  on onchain_anchors   for select using (true);
create policy "public read trace_blobs"      on trace_blobs       for select using (true);
create policy "public read breaker_state"    on breaker_state     for select using (true);
create policy "public read blocklist"        on blocklist         for select using (true);
create policy "public read llm_usage"        on llm_usage         for select using (true);
create policy "public read treasury"         on treasury          for select using (true);
