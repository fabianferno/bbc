-- BBC agent store schema (Supabase / Postgres).
--
-- Derived from agent/store/db.py (the MongoDB DAO) collection by collection.
-- See docs/superpowers/specs/2026-09-09-supabase-migration-design.md for the
-- decisions behind the choices below. The short version:
--
--   * JSON columns are `text`, NEVER `jsonb`. The DAO stores JSON as verbatim
--     strings so on-chain trace hashes stay byte-identical across venues;
--     `jsonb` normalises key order and whitespace and would silently break
--     `/verify/<id>` for every trace already anchored on Solana.
--   * Timestamps are `text` holding ISO-8601 UTC strings (`_now()` in db.py),
--     not `timestamptz` — `positions_today_pnl` prefix-matches on the date,
--     and converting to a real timestamp type would change that semantics.
--   * Integer ids are `bigint generated by default as identity`, replacing
--     the old `counters` collection (`db.next_id`).
--   * `markets` keeps its Mongo `_id` shape: `"{venue}:{external_id}"`, a
--     string primary key (db.py:94). `treasury` keeps the constant string PK
--     `"main"` (agent/treasury/ledger.py: TREASURY_DOC_ID).
--
-- This file is idempotent (`create table if not exists`) so it can be re-run
-- safely. Run it once, in full, in the Supabase SQL editor.

-- ============================================================================
-- markets
-- Derived from: db.py upsert_market (92-124), get_market (127-128),
-- list_resolved_markets (131-140), list_open_markets (143-145),
-- list_tradeable_markets (148-155).
-- ============================================================================
create table if not exists markets (
    id                 text primary key,             -- "{venue}:{external_id}"
    venue              text not null,
    external_id        text not null,
    question           text not null,
    category           text,
    resolution_source  text,
    resolution_rules   text,
    yes_token_id       text,
    no_token_id        text,
    end_date           text,
    closed_time        text,
    resolved           integer not null default 0,
    resolution_value   double precision,
    last_price_yes     double precision,
    volume_24h         double precision,
    book_depth_5c      double precision,
    seen_at            text,
    updated_at         text,
    -- Verbatim JSON of the raw upstream market payload. `text`, not `jsonb`:
    -- see the file header — normalising this would not itself break a hash
    -- (raw is not part of the trace), but every JSON column in this schema
    -- follows one rule for consistency and to avoid a silent exception here
    -- being copy-pasted onto a hash-critical column elsewhere.
    raw                text
);

create index if not exists idx_markets_venue_external on markets (venue, external_id);
create index if not exists idx_markets_resolved_end_date on markets (resolved, end_date);
create index if not exists idx_markets_category on markets (category);

