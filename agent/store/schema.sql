    response_raw    text not null,
    -- Parsed LLM response, verbatim JSON. Hash-critical: part of the
    -- reasoning trace anchored on Solana. Never jsonb.
    response_json   text,
    p_yes           double precision,
    confidence      double precision,
    action          text,
    input_tokens    integer not null default 0,
    output_tokens   integer not null default 0,
    cost_usd        double precision not null default 0.0,
    created_at      text not null
);

create index if not exists idx_decisions_market_kind_created
    on decisions (market_id, kind, created_at);

